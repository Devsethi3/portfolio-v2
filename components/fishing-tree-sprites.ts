export function drawReferenceTrees(
  g: CanvasRenderingContext2D,
  reference: HTMLImageElement,
  ground: number,
) {
  const grove = new Path2D(CANOPY);
  // Bark is sampled from the same reference, under the overlapping foliage.
  grove.rect(69, 209, 15, 52);
  grove.rect(134, 214, 14, 47);
  grove.rect(193, 214, 14, 47);

  const small = new Path2D(SMALL_CANOPY);
  small.rect(193, 214, 14, 47);

  const paint = (shape: Path2D, x: number, scale: number, flip = false) => {
    g.save();
    g.translate(x, ground - 261 * scale);
    g.scale(flip ? -scale : scale, scale);
    g.clip(shape);
    g.imageSmoothingEnabled = false;
    g.drawImage(reference, 0, 0);
    g.restore();
  };

  paint(grove, 0, 0.54);
  paint(small, 144, 0.36);
  paint(grove, 340, 0.5, true);
}
